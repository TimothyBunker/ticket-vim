import assert from 'node:assert/strict';
import extension from '../agent/editor.mjs';
const tools = new Map();
extension({ registerTool: tool => tools.set(tool.name, tool), registerCommand() {} });
const comment = tools.get('editor_comment');
const result = await comment.execute('call-1', { path: 'src/file.py', line_start: 2, body: 'Check this.' }, null, null, { cwd: '/tmp/project' });
assert.equal(result.details.tim.kind, 'comment');
assert.equal(result.details.tim.id, 'call-1');
assert.equal(JSON.parse(result.content[0].text).applied, false);
await assert.rejects(comment.execute('bad', { path: '../outside', line_start: 1 }, null, null, { cwd: '/tmp/project' }));
await assert.rejects(comment.execute('bad', { path: 'src/a', line_start: 3, line_end: 1 }, null, null, { cwd: '/tmp/project' }));
const refreshed = await comment.execute('call-3', { path: 'src/file.py', line_start: 3, body: 'Updated', comment_id: 'call-1' }, null, null, { cwd: '/tmp/project' });
assert.equal(JSON.parse(refreshed.content[0].text).id, 'call-1');
assert.equal(refreshed.details.tim.id, 'call-3');
const proposal = tools.get('editor_propose_diff');
await assert.rejects(proposal.execute('bad', { diff: 'I will fix it' }));
const diff = '--- a/src/file.py\n+++ b/src/file.py\n@@ -1 +1 @@\n-old\n+new';
const posted = await proposal.execute('call-2', { title: 'Fix', diff, comment_id: result.details.tim.id });
assert.equal(posted.details.tim.comment_id, 'call-1');
assert.equal(posted.details.tim.diff, diff);
assert.equal(JSON.parse(posted.content[0].text).applied, false);
assert.deepEqual([...tools.keys()], ['editor_comment', 'editor_propose_diff']);
console.log('PASS structured editor tools publish typed results without an apply/write operation');
